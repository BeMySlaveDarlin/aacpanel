class OutgoingMail(unittest.TestCase):
    def sent(self, to, text="hello"):
        raw = assistant(tool_block("SendMessage", to=to, message=text))
        return chat.parse(json.loads(raw), 0, None)

    def test_a_neighbour_session_address_turns_into_a_name(self):
        import chat.mail as mail
        mail.peer_forget()
        mail._PEER_NAMES[4242] = "docs"
        got = self.sent("uds:/run/user/1000/cc-socks/4242.sock")
        self.assertEqual(got[0]["from"], "docs")

    def test_an_unresolved_name_stays_an_address(self):
        import chat.mail as mail
        mail.peer_forget()
        mail._PEER_NAMES[4243] = ""
        addr = "uds:/run/user/1000/cc-socks/4243.sock"
        self.assertEqual(self.sent(addr)[0]["from"], addr)

    def test_a_name_missing_on_disk_stays_an_address(self):
        import chat.mail as mail
        mail.peer_forget()
        addr = "uds:/run/user/1000/cc-socks/999999.sock"
        self.assertEqual(self.sent(addr)[0]["from"], addr)

    def test_mail_to_a_neighbour_session_is_not_called_agent_mail(self):
        import chat.mail as mail
        mail.peer_forget()
        mail._PEER_NAMES[4242] = "docs"
        self.assertEqual(self.sent("uds:/run/user/1000/cc-socks/4242.sock")[0]["source"],
                         "session")

    def test_mail_to_a_subagent_stays_agent_mail(self):
        self.assertEqual(self.sent("researcher")[0]["source"], "agent")


class DeliveryNotice(unittest.TestCase):
    HELD = ("[Cross-session delivery notice] Your message to another session was held "
            "for the recipient user's approval (recipient: uds:/run/user/1000/cc-socks/17.sock). "
            "Not delivered to that session's Claude yet; its user must approve first. "
            "Do not wait for a reply; continue, or choose another approach.")
    DONE = ("[Cross-session delivery notice] Your message to another session was approved "
            "and released to that session (recipient: uds:/run/user/1000/cc-socks/17.sock).")

    def enqueued(self, text, pending, pos=0):
        raw = line({"type": "queue-operation", "operation": "enqueue",
                    "content": text, "timestamp": "2026-09-04T21:15:02Z"})
        return chat.parse(json.loads(raw), pos, pending)

    def delivered_copy(self, text, pending, pos=1):
        raw = line({"type": "user", "isMeta": True, "promptSource": "system",
                    "timestamp": "2026-09-04T21:15:03Z",
                    "message": {"role": "user", "content": text}})
        return chat.parse(json.loads(raw), pos, pending)

    def test_the_notice_is_not_a_prompt_from_the_owner(self):
        got = self.enqueued(self.DONE, chat.Pending())
        self.assertEqual([(i["role"], i["text"]) for i in got],
                         [("note", "the letter was delivered")])

    def test_it_is_shown_once(self):
        pending = chat.Pending()
