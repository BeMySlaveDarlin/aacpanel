class RepliesWithAttachments(unittest.TestCase):
    def enqueued(self, prompt):
        return {"type": "attachment", "attachment": {"type": "queued_command", "prompt": prompt}}

    def delivered(self, content):
        return {"type": "user", "promptSource": "queued", "origin": {"kind": "human"},
                "message": {"role": "user", "content": content}}

    def test_a_prompt_from_remote_control_is_not_lost(self):
        pend = chat.Pending()
        items = chat.parse(self.enqueued("can we steer the model?"), 0, pending=pend)
        self.assertEqual([i["role"] for i in items], ["me"])
        self.assertEqual(items[0]["text"], "can we steer the model?")
        self.assertEqual(items[0].get("state"), "queued", "a prompt in the queue is marked as waiting")

    def test_a_prompt_with_an_attachment_is_shown_whole(self):
        pend = chat.Pending()
        self.assertEqual(chat.parse({"type": "queue-operation", "operation": "enqueue",
                                     "content": None}, 0, pending=pend), [],
                         "an empty enqueue has nothing to show")
        items = chat.parse(self.enqueued([
            {"type": "image", "source": {"type": "base64", "media_type": "image/jpeg", "data": "AAAA"}},
            {"type": "text", "text": "the input field alignment is off"},
        ]), 10, pending=pend)
        self.assertEqual([i["role"] for i in items], ["shots", "me"],
                         "a screenshot with no words — what the owner saw before the fix")
        self.assertEqual(items[1]["text"], "the input field alignment is off")

    def test_a_prompt_from_the_console_is_not_doubled(self):
        pend = chat.Pending()
        first = chat.parse({"type": "queue-operation", "operation": "enqueue",
                            "content": "look at the logs"}, 0, pending=pend)
        self.assertEqual(len(first), 1)
        self.assertEqual(chat.parse(self.enqueued("look at the logs"), 1, pending=pend), [],
                         "the prompt is shown twice: by the queue record and by the attachment")

    def test_delivery_gives_no_second_bubble(self):
        pend = chat.Pending()
        chat.parse(self.enqueued("look at the logs"), 0, pending=pend)
        got = chat.parse(self.delivered("look at the logs"), 1, pending=pend)
        self.assertEqual([(i["role"], i["pos"]) for i in got], [("me", 0)],
                         "delivery has to fix the prompt in place, not add a second one")

    def test_the_neighbouring_prompt_is_not_doubled(self):
        pend = chat.Pending()
        chat.parse({"type": "queue-operation", "operation": "enqueue", "content": None}, 0, pending=pend)
        chat.parse(self.enqueued([
            {"type": "image", "source": {"type": "base64", "media_type": "image/jpeg", "data": "AA"}},
            {"type": "text", "text": "put the date here"},
        ]), 1, pending=pend)

        chat.parse({"type": "queue-operation", "operation": "enqueue",
                    "content": "the date is better at the bottom"}, 2, pending=pend)
        got = chat.parse(self.delivered("the date is better at the bottom"), 3, pending=pend)
        self.assertEqual([(i["role"], i["pos"]) for i in got], [("me", 2)],
                         "the prompt doubled: delivery showed it in its own place instead of fixing it where it was enqueued")


