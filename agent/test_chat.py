class WakeAcrossPolls(unittest.TestCase):
    def setUp(self):
        self.dir = test_barrier.tmp_dir()
        self.addCleanup(self.dir.cleanup)
        self.path = os.path.join(self.dir.name, f"{UUID}.jsonl")
        self.text = "Keep the loop going: check the queue and pick up a task"
        self.armed = assistant(tool_block("ScheduleWakeup", delaySeconds=300, noop=True,
                                          prompt="<<autonomous-loop-dynamic>>"))
        self.enqueue = line({"type": "queue-operation", "operation": "enqueue",
                             "content": self.text, "timestamp": "2026-08-23T10:00:00Z"})
        self.fire = line({"type": "user", "isMeta": True, "promptSource": "system",
                          "scheduledTaskId": "bbbb2222", "timestamp": "2026-08-23T10:20:00Z",
                          "message": {"content": self.text}})

    def write(self, *raws):
        with open(self.path, "w", encoding="utf-8") as f:
            f.write("".join(raws))

    def test_the_fix_catches_up_with_the_client_on_the_next_poll(self):
        self.write(self.armed, self.enqueue)
        first = chat.feed(self.path, limit=40)
        self.assertEqual([i["role"] for i in first["items"] if i["role"] in ("me", "wake")],
                         ["me"], "before the firing this really is a prompt — there is no way to know otherwise")

        self.write(self.armed, self.enqueue, self.fire)
        more = chat.feed(self.path, limit=40, after=first["last"])
        rows = [i for i in more["items"] if i["role"] == "wake"]
        self.assertEqual(len(rows), 1, "the firing did not arrive")
        self.assertEqual(rows[0]["pos"], first["items"][-1]["pos"],
                         "the fix is addressed to a row other than the one on screen")
        self.assertEqual(rows[0].get("fixes"), "me",
                         "without the flag the client will not merge the card with the bubble and will show both")
