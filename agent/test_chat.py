class ExecutableFile(unittest.TestCase):
    def setUp(self):
        import shutil
        self.root = os.path.realpath(test_barrier.tmp_path())
        self.addCleanup(shutil.rmtree, self.root, ignore_errors=True)
        self.cwd = os.path.join(self.root, "proj")
        os.makedirs(self.cwd)

    def put(self, name, data, mode=0o644):
        path = os.path.join(self.cwd, name)
        with open(path, "wb") as f:
            f.write(data)
        os.chmod(path, mode)
        return path

    def test_the_x_bit_hides_the_contents(self):
        self.put("run.sh", b"echo hi\n", 0o755)
        got = chat.read_file("run.sh", self.cwd)
        self.assertEqual(got["kind"], "exec")
        self.assertNotIn("text", got)
        self.assertNotIn("data", got)
        self.assertEqual(got["name"], "run.sh")
        self.assertEqual(got["size"], len("echo hi\n"))
        self.assertTrue(got["mode"].endswith("rwxr-xr-x"), got["mode"])

    def test_an_x_bit_for_others_counts_the_same(self):
        self.put("tool", b"payload\n", 0o654)
        self.assertEqual(chat.read_file("tool", self.cwd)["kind"], "exec")

    def test_a_compiled_program_header_without_the_x_bit(self):
        for name, head in (("bin", b"\x7fELF\x02\x01"), ("app.dll", b"MZ\x90\x00")):
            self.put(name, head + b"\x00tail", 0o644)
            got = chat.read_file(name, self.cwd)
            self.assertEqual(got["kind"], "exec", name)
            self.assertNotIn("text", got, name)

    def test_the_x_bit_decides_not_the_shebang(self):
        body = b"#!/usr/bin/env python3\nprint('hi')\n"
        path = self.put("tool.py", body, 0o644)

        got = chat.read_file("tool.py", self.cwd)
        self.assertEqual(got["kind"], "text")
        self.assertIn("print('hi')", got["text"])

        os.chmod(path, 0o755)
        got = chat.read_file("tool.py", self.cwd)
        self.assertEqual(got["kind"], "exec")
        self.assertNotIn("text", got)

    def test_a_program_named_like_an_image_does_not_travel_as_an_image(self):
        self.put("logo.png", b"\x7fELF\x02\x01" + b"\x00" * 64, 0o755)
        got = chat.read_file("logo.png", self.cwd)
        self.assertEqual(got["kind"], "exec")
        self.assertNotIn("data", got)
        self.assertNotIn("media", got)

    def test_an_ordinary_file_does_not_become_a_program(self):
        self.put("notes.sh", b"# just a note\n", 0o644)
        got = chat.read_file("notes.sh", self.cwd)
        self.assertEqual(got["kind"], "text")
        self.assertIn("just a note", got["text"])


