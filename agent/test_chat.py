def line(record):
    return json.dumps(record, ensure_ascii=False) + "\n"


def user(text):
    return line({"type": "user", "message": {"content": text}, "timestamp": "2026-08-23T10:00:00Z"})


def local_command(text):
    return line({"type": "system", "subtype": "local_command", "content": text,
                 "level": "info", "timestamp": "2026-08-23T10:00:00Z"})


def assistant(*blocks):
    return line({"type": "assistant", "message": {"content": list(blocks)},
                 "timestamp": "2026-08-23T10:00:01Z"})


def text_block(text):
    return {"type": "text", "text": text}


def tool_block(name, **kwargs):
    return {"type": "tool_use", "name": name, "input": kwargs}


class Parse(unittest.TestCase):
    def items(self, raw):
        return chat.parse(json.loads(raw), 0)

    def test_a_human_prompt_reaches_the_feed(self):
        got = self.items(user("task status in detail"))
        self.assertEqual([(i["role"], i["text"]) for i in got],
                         [("me", "task status in detail")])

    def test_a_tool_result_is_not_a_human_prompt(self):
        raw = line({"type": "user", "message": {"content": [
            {"type": "tool_result", "content": "ok"},
        ]}})
        self.assertEqual(self.items(raw), [])

    def test_a_system_reminder_is_not_a_prompt(self):
        self.assertEqual(self.items(user("<system-reminder>remember about X</system-reminder>")), [])

    def test_an_interruption_shows_as_a_note_not_a_prompt(self):
        got = self.items(user("[Request interrupted by user]"))
        self.assertEqual([(i["role"], i["text"]) for i in got], [("note", "the human interrupted the answer")])

    def test_harness_mechanics_stay_out_of_the_feed(self):
        for text in (
            "Base directory for this skill: /home/u/.claude/plugins/x",
            "Skill /planner:finalize is already loaded above; instructions unchanged.",
            "Caveat: The messages below were generated by the user while running local commands. DO NOT...",
        ):
            self.assertEqual(self.items(user(text)), [], text[:40])

    def test_a_slash_command_shows_as_a_prompt(self):
        got = self.items(user("<command-name>/model</command-name>\n"
                              "            <command-message>model</command-message>\n"
                              "            <command-args></command-args>"))
        self.assertEqual([(i["role"], i["text"]) for i in got], [("me", "/model")])

    def test_a_slash_command_answer_arrives_as_a_note(self):
        got = self.items(local_command(
            "<local-command-stdout>Kept model as `Opus 5`</local-command-stdout>"))
        self.assertEqual([(i["role"], i["text"]) for i in got],
                         [("note", "Kept model as `Opus 5`")])

    def test_a_command_refusal_arrives_the_same_way_as_success(self):
        got = self.items(local_command(
            "<local-command-stdout>Model 'fable xhigh' not found</local-command-stdout>"))
        self.assertEqual([(i["role"], i["text"]) for i in got],
                         [("note", "Model 'fable xhigh' not found")])
        got = self.items(user(
            "<local-command-stderr>Error during compaction: API Error: 529</local-command-stderr>"))
        self.assertEqual([(i["role"], i["text"]) for i in got],
                         [("note", "Error during compaction: API Error: 529")])

    def test_a_command_answer_arrives_in_two_kinds_of_records(self):
        got = self.items(user(
            "<local-command-stdout>Set model to `Fable 5.1`</local-command-stdout>"))
        self.assertEqual([(i["role"], i["text"]) for i in got],
                         [("note", "Set model to `Fable 5.1`")])

    def test_terminal_coloring_is_stripped_from_the_answer(self):
        got = self.items(local_command(
            "<local-command-stdout>Set model to \x1b[1mFable 5\x1b[22m</local-command-stdout>"))
        self.assertEqual(got[0]["text"], "Set model to Fable 5")

    def test_an_empty_command_answer_does_not_become_a_note(self):
        self.assertEqual(self.items(local_command(
            "<local-command-stdout></local-command-stdout>")), [])

    def test_a_long_command_answer_names_the_trim(self):
        got = self.items(local_command(
            "<local-command-stdout>" + "x" * 5000 + "</local-command-stdout>"))
        self.assertLess(len(got[0]["text"]), 5000)
        self.assertTrue(got[0]["text"].endswith("…"), got[0]["text"][-20:])

    def test_a_slash_command_in_its_own_record_is_a_prompt_too(self):
        got = self.items(local_command("<command-name>/model</command-name>\n"
                                       "            <command-message>model</command-message>\n"
                                       "            <command-args>fable xhigh</command-args>"))
        self.assertEqual([(i["role"], i["text"]) for i in got], [("me", "/model fable xhigh")])

    def test_the_arguments_stay_with_the_command(self):
        got = self.items(user("<command-name>/model</command-name>\n"
                              "            <command-message>model</command-message>\n"
                              "            <command-args>fable xhigh</command-args>"))
        self.assertEqual([(i["role"], i["text"]) for i in got], [("me", "/model fable xhigh")])

    def test_other_system_records_stay_out_of_the_feed(self):
        self.assertEqual(self.items(line({"type": "system", "subtype": "stop_hook_summary",
                                          "content": "hook ok"})), [])

    def test_a_request_to_run_a_skill_stays_a_prompt(self):
        got = self.items(user("Run the skill `ts` with arguments: list"))
        self.assertEqual(got[0]["role"], "me")

    def test_an_interruption_and_a_compaction_stay_notes(self):
        self.assertEqual(self.items(user("[Request interrupted by user]"))[0]["role"], "note")
        self.assertEqual(self.items(user("This session is being continued from a previous conversation "
                                         + "that ran out of context."))[0]["role"], "note")

    def test_the_summary_after_a_compaction_is_a_note(self):
        got = self.items(user("This session is being continued from a previous conversation that ran out of context. "
                              + "The summary below covers " + "x" * 5000))
        self.assertEqual(got[0]["role"], "note")
        self.assertLess(len(got[0]["text"]), 100)

    def test_model_text_and_calls_come_in_order(self):
        raw = assistant(text_block("Looking"), tool_block("Bash", command="ls -la"),
                        text_block("Found it"))
        got = self.items(raw)
        self.assertEqual([i["role"] for i in got], ["ai", "tool", "ai"])
        self.assertEqual(got[1]["name"], "Bash")
        self.assertEqual(got[1]["arg"], "ls -la")

    def test_a_multiline_command_stays_one_line(self):
        raw = assistant(tool_block("Bash", command="cd /tmp\nls"))
        self.assertNotIn("\n", self.items(raw)[0]["arg"])

    def test_subagent_work_stays_out_of_the_feed(self):
        raw = line({"type": "assistant", "isSidechain": True,
                    "message": {"content": [text_block("I am a subagent")]}})
        self.assertEqual(self.items(raw), [])

    def test_service_records_are_skipped(self):
        for kind in ("attachment", "system", "file-history-snapshot", "mode", "custom-title"):
            self.assertEqual(self.items(line({"type": kind, "payload": 1})), [], kind)

    def test_a_long_prompt_is_trimmed_and_says_so(self):
        got = self.items(user("x" * (chat.MAX_TEXT + 500)))[0]
        self.assertEqual(len(got["text"]), chat.MAX_TEXT)
        self.assertTrue(got["cut"])

    def test_a_short_prompt_is_not_marked_trimmed(self):
        self.assertFalse(self.items(user("short"))[0]["cut"])


class ShellCommands(unittest.TestCase):
    """A command the human runs from the console with the ! prefix."""

    def setUp(self):
        self.dir = test_barrier.tmp_dir()
        self.addCleanup(self.dir.cleanup)
        self.path = os.path.join(self.dir.name, f"{UUID}.jsonl")

    def items(self, raw):
        return chat.parse(json.loads(raw), 0)

    def write(self, *raws):
        with open(self.path, "w", encoding="utf-8") as f:
            for raw in raws:
                f.write(raw)

    def call(self, tool_id, command):
        return assistant({"type": "tool_use", "id": tool_id, "name": "Bash",
                          "input": {"command": command}})

    def answer(self, tool_id, body):
        return line({"type": "user", "timestamp": "2026-08-23T10:00:02Z",
                     "message": {"content": [{"type": "tool_result", "tool_use_id": tool_id,
                                              "content": body}]}})

    def test_the_command_is_not_a_prompt(self):
        got = self.items(user("<bash-input>stand/creds-push.sh</bash-input>"))
        self.assertEqual([(i["role"], i["text"]) for i in got],
                         [("shell", "stand/creds-push.sh")])

    def test_the_command_loses_the_space_around_it(self):
        got = self.items(user("<bash-input>  ls -la  </bash-input>"))
        self.assertEqual(got[0]["text"], "ls -la")

    def test_a_multiline_command_keeps_its_lines(self):
        got = self.items(user("<bash-input>for f in a b; do\n  echo $f\ndone</bash-input>"))
        self.assertEqual(got[0]["text"], "for f in a b; do\n  echo $f\ndone")

    def test_the_output_comes_apart_from_the_command(self):
        got = self.items(user("<bash-stdout>pushed 3 files</bash-stdout>"
                              "<bash-stderr>warning: slow link</bash-stderr>"))
        self.assertEqual([(i["role"], i["text"], i["err"]) for i in got],
                         [("shellout", "pushed 3 files", "warning: slow link")])

    def test_an_empty_error_stream_leaves_no_trace(self):
        got = self.items(user("<bash-stdout>pushed 3 files</bash-stdout><bash-stderr></bash-stderr>"))
        self.assertEqual(len(got), 1)
        self.assertNotIn("err", got[0])
        self.assertEqual(got[0]["text"], "pushed 3 files")

    def test_an_error_with_no_output_still_arrives(self):
        got = self.items(user("<bash-stdout></bash-stdout><bash-stderr>no such file</bash-stderr>"))
        self.assertEqual([(i["role"], i["text"], i["err"]) for i in got],
                         [("shellout", "", "no such file")])

    def test_a_silent_command_gives_an_empty_output_row(self):
        got = self.items(user("<bash-stdout></bash-stdout><bash-stderr></bash-stderr>"))
        self.assertEqual([(i["role"], i["text"]) for i in got], [("shellout", "")])

    def test_the_output_is_read_back_from_its_escaping(self):
        got = self.items(user("<bash-stdout>a &gt; b &amp;&amp; c &lt; d</bash-stdout>"
                              "<bash-stderr>2&gt;&amp;1</bash-stderr>"))
        self.assertEqual((got[0]["text"], got[0]["err"]), ("a > b && c < d", "2>&1"))

    def test_the_output_keeps_its_own_line_breaks(self):
        got = self.items(user("<bash-stdout>one\ntwo\n  three</bash-stdout><bash-stderr></bash-stderr>"))
        self.assertEqual(got[0]["text"], "one\ntwo\n  three")

    def test_a_long_output_is_trimmed_and_says_so(self):
        got = self.items(user("<bash-stdout>" + "x" * 40000 + "</bash-stdout><bash-stderr></bash-stderr>"))
        self.assertLess(len(got[0]["text"]), 40000)
        self.assertTrue(got[0]["cut"])

    def test_a_short_output_is_not_marked_trimmed(self):
        got = self.items(user("<bash-stdout>ok</bash-stdout><bash-stderr></bash-stderr>"))
        self.assertFalse(got[0]["cut"])

    def test_the_rows_carry_their_time_and_place(self):
        got = self.items(user("<bash-input>ls</bash-input>"))
        self.assertEqual((got[0]["at"], got[0]["pos"]), ("2026-08-23T10:00:00Z", 0))

    def test_a_prompt_that_mentions_the_tag_stays_a_prompt(self):
        got = self.items(user("what does <bash-input> mean in the transcript?"))
        self.assertEqual([(i["role"], i["text"]) for i in got],
                         [("me", "what does <bash-input> mean in the transcript?")])

    def test_a_plain_prompt_is_untouched(self):
        got = self.items(user("task status in detail"))
        self.assertEqual([(i["role"], i["text"]) for i in got], [("me", "task status in detail")])

    def test_the_command_does_not_enter_the_queue(self):
        pending = chat.Pending()
        chat.parse(json.loads(user("<bash-input>ls</bash-input>")), 0, pending)
        self.assertFalse(pending.seen("ls"))

    def test_the_command_breaks_a_run_of_calls(self):
        self.write(self.call("t1", "ls"), self.answer("t1", "one"),
                   user("<bash-input>make check</bash-input>"),
                   user("<bash-stdout>ok</bash-stdout><bash-stderr></bash-stderr>"),
                   self.call("t2", "pwd"), self.answer("t2", "two"))
        items = chat.feed(self.path)["items"]
        self.assertEqual([i["role"] for i in items], ["tools", "shell", "shellout", "tools"])


class Queue(unittest.TestCase):
    def items(self, raw, pending=None):
        return chat.parse(json.loads(raw), 0, pending)

    def enqueued(self, text, pending, pos=0):
        raw = line({"type": "queue-operation", "operation": "enqueue",
                    "content": text, "timestamp": "2026-08-23T10:00:00Z"})
        return chat.parse(json.loads(raw), pos, pending)

    def test_an_alarm_is_not_a_human_prompt(self):
        pending = chat.Pending()
        self.items(assistant(tool_block("ScheduleWakeup", delaySeconds=1200,
                                        prompt="Watch tick: check CI")), pending)
        got = self.enqueued("Watch tick: check CI", pending)
        self.assertEqual([(i["role"], i["text"]) for i in got],
                         [("wake", "Watch tick: check CI")])
        fired = line({"type": "user", "isMeta": True, "promptSource": "system",
                      "scheduledTaskId": "bbbb2222", "timestamp": "2026-08-23T10:20:00Z",
                      "message": {"content": "Watch tick: check CI"}})
        self.assertEqual(self.items(fired, pending), [], "the firing is shown a second time")

    def test_a_firing_with_no_enqueue_is_an_alarm_too(self):
        fired = line({"type": "user", "isMeta": True, "promptSource": "system",
                      "scheduledTaskId": "bbbb2222", "timestamp": "2026-08-23T10:20:00Z",
                      "message": {"content": "Watch tick: check CI"}})
        got = self.items(fired, chat.Pending())
        self.assertEqual([(i["role"], i["text"]) for i in got],
                         [("wake", "Watch tick: check CI")])

    def test_the_autonomous_loop_fixes_the_bubble_already_shown(self):
        pending = chat.Pending()
        self.items(assistant(tool_block("ScheduleWakeup", delaySeconds=300, noop=True,
                                        prompt="<<autonomous-loop-dynamic>>")), pending)
        instructions = "Keep the loop going: check the queue and pick up a task"
        shown = self.enqueued(instructions, pending, pos=140)
        self.assertEqual([(i["role"], i["text"]) for i in shown],
                         [("me", instructions)], "the enqueue could not have been recognized")

        fired = line({"type": "user", "isMeta": True, "promptSource": "system",
                      "scheduledTaskId": "bbbb2222", "timestamp": "2026-08-23T10:20:00Z",
                      "message": {"content": instructions}})
        got = chat.parse(json.loads(fired), 900, pending)
        self.assertEqual([(i["role"], i["text"]) for i in got],
                         [("wake", instructions)], "the firing said nothing — the bubble stayed")
        self.assertEqual(got[0]["pos"], 140,
                         "the card stands in its own place, not where the firing landed")
        self.assertEqual(got[0].get("fixes"), "me",
                         "without this the fix has nothing to find: the address is the position and the role")

    def test_a_recognized_enqueue_gives_no_second_card(self):
        pending = chat.Pending()
        self.items(assistant(tool_block("ScheduleWakeup", delaySeconds=1200,
                                        prompt="Watch tick: check CI")), pending)
        self.enqueued("Watch tick: check CI", pending, pos=140)
        fired = line({"type": "user", "isMeta": True, "promptSource": "system",
                      "scheduledTaskId": "bbbb2222", "timestamp": "2026-08-23T10:20:00Z",
                      "message": {"content": "Watch tick: check CI"}})
        self.assertEqual(chat.parse(json.loads(fired), 900, pending), [])

    def test_a_human_prompt_does_not_become_an_alarm(self):
        pending = chat.Pending()
        self.items(assistant(tool_block("ScheduleWakeup", delaySeconds=300, noop=True,
                                        prompt="<<autonomous-loop-dynamic>>")), pending)
        got = self.enqueued("take a look at what the run is doing", pending, pos=140)
        self.assertEqual([(i["role"], i["text"]) for i in got],
                         [("me", "take a look at what the run is doing")])

    def test_a_letter_from_the_panel_does_not_count_as_an_alarm(self):
        record = line({"type": "user", "isMeta": True, "promptSource": "system",
                       "origin": {"kind": "peer", "from": "aacpanel-panel"},
                       "message": {"content": "hello"}})
        got = self.items(record, chat.Pending())
        self.assertNotIn("wake", [i["role"] for i in got])

    def test_a_prompt_typed_mid_turn_reaches_the_feed(self):
        raw = line({"type": "queue-operation", "operation": "enqueue",
                    "content": "change the color scheme", "timestamp": "2026-08-23T10:00:00Z"})
        self.assertEqual([(i["role"], i["text"]) for i in self.items(raw)],
                         [("me", "change the color scheme")])

    def test_while_it_waits_in_the_queue_it_is_marked(self):
        got = self.enqueued("change the scheme", chat.Pending())
        self.assertEqual(got[0]["state"], "queued")

    def test_the_mark_goes_when_it_reaches_the_model_between_turns(self):
        pending = chat.Pending()
        self.enqueued("change the scheme", pending, pos=10)
        raw = line({"type": "queue-operation", "operation": "dequeue"})
        fixed = self.items(raw, pending)
        self.assertEqual(len(fixed), 1)
        self.assertEqual(fixed[0]["pos"], 10)
        self.assertNotIn("state", fixed[0])

    def test_a_delivered_prompt_gives_no_second_bubble(self):
        pending = chat.Pending()
        self.enqueued("change the scheme", pending, pos=10)
        self.items(line({"type": "queue-operation", "operation": "dequeue"}), pending)
        raw = line({"type": "user", "promptSource": "queued", "timestamp": "2026-08-23T10:01:00Z",
                    "message": {"content": "change the scheme"}})
        self.assertEqual(chat.parse(json.loads(raw), 99, pending), [])

    def test_a_prompt_from_the_terminal_does_not_touch_the_queue(self):
        pending = chat.Pending()
        self.enqueued("yes", pending, pos=10)
        raw = line({"type": "user", "timestamp": "2026-08-23T10:01:00Z",
                    "message": {"content": "yes"}})
        got = chat.parse(json.loads(raw), 99, pending)
        self.assertEqual([(i["role"], i["pos"]) for i in got], [("me", 99)])

    def test_the_mark_goes_by_text_when_it_leaves_inside_a_turn(self):
        pending = chat.Pending()
        self.enqueued("first", pending, pos=10)
        self.enqueued("second", pending, pos=20)
        raw = line({"type": "queue-operation", "operation": "remove", "content": "second"})
        fixed = self.items(raw, pending)
        self.assertEqual([(i["pos"], "state" in i) for i in fixed], [(20, False)])

    def test_identical_prompts_are_cleared_one_after_another(self):
        pending = chat.Pending()
        self.enqueued("yes", pending, pos=10)
        self.enqueued("yes", pending, pos=20)
        first = self.items(line({"type": "queue-operation", "operation": "dequeue"}), pending)
        second = self.items(line({"type": "queue-operation", "operation": "dequeue"}), pending)
        self.assertEqual([first[0]["pos"], second[0]["pos"]], [10, 20])

    def test_leaving_an_empty_queue_changes_nothing(self):
        for op in ("dequeue", "remove", "clear"):
            got = self.items(line({"type": "queue-operation", "operation": op,
                                   "content": "what was never there"}), chat.Pending())
            self.assertEqual(got, [], op)

    def test_an_empty_queue_record_is_skipped(self):
        raw = line({"type": "queue-operation", "operation": "enqueue", "content": "   "})
        self.assertEqual(self.items(raw), [])


